#!/usr/bin/env python3
"""Overlay ca65 patches onto a user-supplied stock KERNAL.

usage: build.py STOCK.bin OUT.bin [-D NAME=VALUE ...] [--patches DIR]
       build.py --table OUT.h [-D NAME=VALUE ...] [--patches DIR]

Patch sources use segments named P_XXXX (XXXX = hex load address). Each
segment is linked at that address and copied over the stock image.
Stock ROM bytes are never stored in this repo.

--table writes the segments as a C header instead (VD_KernalPatch[]: runs of address hi, lo, length hi, lo, bytes; a zero length
ends it), for the firmware to patch the C64's own KERNAL in memory (firmware/IOH_TDrive.c, VD_KernalPatchApply). No stock ROM is
read: the runs are our bytes only.
"""
import pathlib, re, subprocess, sys, tempfile

root = pathlib.Path(__file__).resolve().parent.parent
args = sys.argv[1:]
table = None
if "--table" in args:
    i = args.index("--table"); table = pathlib.Path(args[i + 1]); del args[i:i + 2]
    stock = bytes(8192)
else:
    stock = pathlib.Path(args[0]).read_bytes(); out = pathlib.Path(args[1]); del args[:2]
    assert len(stock) == 8192, "stock KERNAL must be 8192 bytes"
patch_dir = root / "patches"
if "--patches" in args:
    i = args.index("--patches"); patch_dir = pathlib.Path(args[i + 1]).resolve(); del args[i:i + 2]
defs = [a for a in args if a != "-D"]
img = bytearray(stock)

srcs = sorted(patch_dir.glob("*.s"))
segs = sorted({m for s in srcs for m in re.findall(r'\.segment\s+"P_([0-9A-Fa-f]{4})"', s.read_text())})

if table is None and "EA32" in segs:   # the border flash retargets the IRQ routine's `JSR $FFEA` (UDTIM): refuse to patch a ROM that does not have it
    assert stock[0xEA31 - 0xE000:0xEA34 - 0xE000] == bytes([0x20, 0xEA, 0xFF]), "no JSR $FFEA at $EA31: not a 901227-03 KERNAL?"
if table is None and "E1DA" in segs:   # the default LOAD/SAVE device is the operand of `LDX #$01` at $E1D9
    assert stock[0xE1D9 - 0xE000:0xE1DB - 0xE000] == bytes([0xA2, 0x01]), "no LDX #$01 at $E1D9: not a 901227-03 KERNAL?"
if table is None and "E5EE" in segs:   # SHIFT+RUN: the editor's `LDX #n / SEI / STX $C6` that fills the keyboard buffer (n = 9; 15 on the SX-64)
    assert stock[0xE5EE - 0xE000] == 0xA2 and stock[0xE5F0 - 0xE000:0xE5F3 - 0xE000] == bytes([0x78, 0x86, 0xC6]), "no SHIFT+RUN buffer fill at $E5EE: not a 901227-03 KERNAL?"
if table is None and "E43D" in segs:   # the banner (patches/vdbanner.s) rewrites the strings INITMS prints and its closing `JMP $A644`
    assert stock[0xE429 - 0xE000:0xE447 - 0xE000] == bytes.fromhex("a973a0e4201eaba537 38e52baaa538e52c20cdbd a960a0e4201eab4c44a6".replace(" ", "")), \
        "INITMS at $E429 is not the 901227-03 one (strings at $E473 / $E460, JMP $A644)"
    assert stock[0xE49A - 0xE000:0xE4AC - 0xE000] == b" 64K RAM SYSTEM  \0", "no \" 64K RAM SYSTEM  \" at $E49A: the banner's stock line prints it from there"

with tempfile.TemporaryDirectory() as t:
    t = pathlib.Path(t)
    objs = []
    for s in srcs:
        o = t / (s.stem + ".o")
        cmd = ["ca65", "-o", str(o)]
        for d in defs: cmd += ["-D", d]
        subprocess.run(cmd + [str(s)], check=True)
        objs.append(str(o))
    mem, sg = [], []
    for a in segs:
        mem.append(f'M{a}: start = ${a}, size = $0800, file = "{t}/{a}.bin";')
        sg.append(f"P_{a}: load = M{a}, type = ro;")
    cfg = t / "k.cfg"
    cfg.write_text("MEMORY {\n" + "\n".join(mem) + "\n}\nSEGMENTS {\n" + "\n".join(sg) + "\n}\n")
    subprocess.run(["ld65", "-C", str(cfg), "-o", str(t / "x.bin"), *objs], check=True)
    runs = []
    for a in segs:
        addr = int(a, 16)
        data = (t / f"{a}.bin").read_bytes()
        assert 0xE000 <= addr and addr + len(data) <= 0x10000, f"P_{a} out of range"
        img[addr - 0xE000 : addr - 0xE000 + len(data)] = data
        runs.append((addr, data))
        if table is None: print(f"P_{a}: {len(data)} bytes")

if table is None:
    out.write_bytes(img)
else:
    body = bytearray()
    for addr, data in runs: body += bytes([addr >> 8, addr & 0xFF, len(data) >> 8, len(data) & 0xFF]) + data
    body += bytes(4)
    rows = ",\n".join("   " + ", ".join("0x%02x" % b for b in body[i:i + 16]) for i in range(0, len(body), 16))
    table.write_text("// The TDrive KERNAL patches (teensyrom-vdrive patches/*.s), generated by tools/build.py --table: runs of address hi, lo,\n"
                     "// length hi, lo and the bytes, a zero length at the end. Our code only: the firmware lays it over the C64's own KERNAL.\n"
                     "#pragma once\n#define VD_KernalPatchBytes %d   // bytes laid over the KERNAL\n"
                     "static const uint8_t VD_KernalPatch[] PROGMEM = {\n%s\n};\n" % (sum(len(d) for _, d in runs), rows))
