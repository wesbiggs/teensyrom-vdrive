#!/usr/bin/env python3
"""Assemble the plain TeensyROM's agent (vector/vdagent.s) and its hook block (vector/vdhooks.s) for the firmware and write them as a C header.

usage: build_agent.py OUT.h [--vice OUT.prg]

Hardware layout (docs/DESIGN.md 51): linked at $DE08 (IO1, after the SwiftLink ACIA's $DE00-$DE07), the mailbox registers at
IO2 $DF00-$DF0A and the window at $DF80. The header holds VD_AgentBase and VD_Agent[] (the bytes from $DE08), which
firmware/IOH_VDriveAgent.c serves from IO1, and VD_HooksBase / VD_Hooks[] (the hook block, at $DF10 = the registers + $10, served from
IO2; docs/DESIGN.md 53). --vice also writes the VICE build of the agent (mailbox in RAM at $C800 / $CA00) as a PRG."""
import pathlib, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE, MBX, WIN = 0xDE08, 0xDF00, 0xDF80
HOOKS = MBX + 0x10


def assemble(base, mbx, win, out, src="vector/vdagent.s"):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / "a.o"
        subprocess.run(["ca65", "-I", str(ROOT / "patches"), "-D", "MBX=$%04X" % mbx, "-D", "WIN=$%04X" % win, "-o", str(o),
                        str(ROOT / src)], check=True)
        subprocess.run(["ld65", "-C", str(ROOT / "vector/agent.cfg"), "-S", "0x%04X" % base, "-o", str(out), str(o)], check=True)
    return pathlib.Path(out).read_bytes()


def main():
    args = sys.argv[1:]
    out = pathlib.Path(args[0])
    with tempfile.TemporaryDirectory() as t:
        prg = assemble(BASE, MBX, WIN, pathlib.Path(t) / "agent.prg")
    assert prg[:2] == bytes([BASE & 0xFF, BASE >> 8])
    code = prg[2:]
    assert BASE + len(code) <= 0xDF00, "the agent must end inside IO1"
    with tempfile.TemporaryDirectory() as t:
        hp = assemble(HOOKS, MBX, WIN, pathlib.Path(t) / "hooks.prg", "vector/vdhooks.s")
    assert hp[:2] == bytes([HOOKS & 0xFF, HOOKS >> 8])
    hooks = hp[2:]
    assert HOOKS + len(hooks) <= WIN, "the hook block must end before the window"
    def rows_of(b): return ",\n".join("   " + ", ".join("0x%02x" % x for x in b[i:i + 16]) for i in range(0, len(b), 16))
    rows = rows_of(code)
    out.write_text("// The plain TeensyROM's agent (teensyrom-vdrive vector/vdagent.s), generated by tools/build_agent.py: served from IO1\n"
                   "// at VD_AgentBase, mailbox registers at IO2 $DF00, window at $DF80 (docs/DESIGN.md 51).\n"
                   "#pragma once\n#define VD_AgentBase 0x%04X\n#define VD_AgentRegs 0x00   // IO2 offset of the registers\n"
                   "static const uint8_t VD_Agent[%d] PROGMEM = {\n%s\n};\n"
                   "// vector/vdhooks.s: served from IO2 at VD_HooksBase (KEYLOG / CINV hooks)\n#define VD_HooksBase 0x%04X\n"
                   "static const uint8_t VD_Hooks[%d] PROGMEM = {\n%s\n};\n" % (BASE, len(code), rows, HOOKS, len(hooks), rows_of(hooks)))
    if "--vice" in args:
        assemble(BASE, 0xC800, 0xCA00, args[args.index("--vice") + 1])


if __name__ == "__main__":
    main()
