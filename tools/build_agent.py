#!/usr/bin/env python3
"""Assemble the plain TeensyROM's agent (vector/vdagent.s) for the firmware and write it as a C header.

usage: build_agent.py OUT.h [--vice OUT.prg]

Hardware layout (docs/DESIGN.md 46): linked at $DE08 (IO1, after the SwiftLink ACIA's $DE00-$DE07), the mailbox registers at
IO2 $DF00-$DF0A and the window at $DF80. The header holds VD_AgentBase and VD_Agent[] (the bytes from $DE08), which
firmware/IOH_VDriveAgent.c serves from IO1. --vice also writes the VICE build (mailbox in RAM at $C800 / $CA00) as a PRG."""
import pathlib, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE, MBX, WIN = 0xDE08, 0xDF00, 0xDF80


def assemble(base, mbx, win, out):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / "a.o"
        subprocess.run(["ca65", "-I", str(ROOT / "patches"), "-D", "MBX=$%04X" % mbx, "-D", "WIN=$%04X" % win, "-o", str(o),
                        str(ROOT / "vector/vdagent.s")], check=True)
        subprocess.run(["ld65", "-C", str(ROOT / "vector/agent.cfg"), "-S", "0x%04X" % base, "-o", str(out), str(o)], check=True)
    return pathlib.Path(out).read_bytes()


def main():
    args = sys.argv[1:]
    out = pathlib.Path(args[0])
    with tempfile.TemporaryDirectory() as t:
        prg = assemble(BASE, MBX, WIN, pathlib.Path(t) / "agent.prg")
    assert prg[:2] == bytes([BASE & 0xFF, BASE >> 8])
    code = prg[2:]
    assert BASE + len(code) <= 0xDF00, "the agent must end inside IO1"
    rows = ",\n".join("   " + ", ".join("0x%02x" % b for b in code[i:i + 16]) for i in range(0, len(code), 16))
    out.write_text("// The plain TeensyROM's agent (teensyrom-vdrive vector/vdagent.s), generated by tools/build_agent.py: served from IO1\n"
                   "// at VD_AgentBase, mailbox registers at IO2 $DF00, window at $DF80 (docs/DESIGN.md 46).\n"
                   "#pragma once\n#define VD_AgentBase 0x%04X\n#define VD_AgentRegs 0x00   // IO2 offset of the registers\n"
                   "static const uint8_t VD_Agent[%d] PROGMEM = {\n%s\n};\n" % (BASE, len(code), rows))
    if "--vice" in args:
        assemble(BASE, 0xC800, 0xCA00, args[args.index("--vice") + 1])


if __name__ == "__main__":
    main()
